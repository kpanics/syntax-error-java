//! The client's menu and HUD in the game's language: their words are kept in English (settings are saved and found by
//! their English names, options by their English words) and shown in Russian when the game is (menus::lang). Module
//! names stay English everywhere.

use std::collections::HashMap;
use std::sync::OnceLock;

pub use crate::menus::lang::Lang;

pub fn lang() -> Lang {
    crate::menus::lang::lang()
}

/// Russian (the few words still written out by hand for it: plurals, dates).
pub fn ru() -> bool {
    lang() == Lang::Ru
}

/// The words the player changed (the words page): by the client's English, what it is changed to.
static WORDS: std::sync::RwLock<Option<HashMap<String, &'static str>>> = std::sync::RwLock::new(None);

/// A word changed by the player, if it is.
pub fn word(key: &str) -> Option<&'static str> {
    WORDS.read().ok()?.as_ref()?.get(key).copied()
}

/// A word changed (None: back to the client's own).
pub fn set_word(key: &str, v: Option<&str>) {
    let mut w = WORDS.write().unwrap();
    let map = w.get_or_insert_with(HashMap::new);
    match v {
        Some(v) => {
            map.insert(key.to_string(), Box::leak(v.to_string().into_boxed_str()));
        }
        None => {
            map.remove(key);
        }
    }
}

pub fn clear_words() {
    if let Ok(mut w) = WORDS.write() {
        *w = None;
    }
}

/// Every changed word (the settings' file keeps them, sorted).
pub fn words_now() -> Vec<(String, String)> {
    let mut v: Vec<(String, String)> = WORDS.read().ok().and_then(|w| w.as_ref().map(|m| m.iter().map(|(k, v)| (k.clone(), v.to_string())).collect())).unwrap_or_default();
    v.sort();
    v
}

/// Every word the client has (its English).
pub fn keys() -> Vec<&'static str> {
    RU.iter().map(|p| p.0).collect()
}

/// A module's name: English everywhere, unless the player changed it.
pub fn nm(s: &str) -> &str {
    match word(s) {
        Some(w) => w,
        None => s,
    }
}

/// `s` as shown: the player's word for it, else in the game's language when there is a word for it, else as it is.
pub fn tr(s: &str) -> &str {
    if let Some(w) = word(s) {
        return w;
    }
    plain(s)
}

/// `s` in the game's language, whatever the player changed it to.
pub fn plain(s: &str) -> &str {
    match lang() {
        Lang::En => s,
        Lang::Ru => {
            static MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
            MAP.get_or_init(|| RU.iter().copied().collect()).get(s).copied().unwrap_or(s)
        }
        Lang::Uk => {
            static MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
            MAP.get_or_init(|| super::i18n_more::MORE.iter().map(|t| (t.0, t.1)).collect()).get(s).copied().unwrap_or(s)
        }
        Lang::Kk => {
            static MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
            MAP.get_or_init(|| super::i18n_more::MORE.iter().map(|t| (t.0, t.2)).collect()).get(s).copied().unwrap_or(s)
        }
    }
}

/// `tr(template)` with its {names} filled.
pub fn trn(template: &str, args: &[(&str, String)]) -> String {
    let mut s = tr(template).to_string();
    for (k, v) in args {
        s = s.replace(&format!("{{{k}}}"), v);
    }
    s
}

/// English or Russian by the game's language (Ukrainian and Kazakh take the English through their tables).
pub fn pick<'a>(en: &'a str, ru_: &'a str) -> &'a str {
    match lang() {
        Lang::Ru => ru_,
        Lang::En => en,
        _ => tr(en),
    }
}

