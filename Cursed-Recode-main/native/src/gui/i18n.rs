/// A unit after a number (" blocks", " ms"…).
pub fn unit(u: &str) -> &str {
    match lang() {
        Lang::En => return u,
        Lang::Uk => {
            return match u {
                " blocks" => " бл.",
                " chunks" => " чанк.",
                " hearts" => " серд.",
                " ticks" => " тік.",
                " ms" => " мс",
                " px" => " пкс",
                " s" => " с",
                " fights" => " боїв",
                "% of usual" => "% від звичайної",
                _ => u,
            }
        }
        Lang::Kk => {
            return match u {
                " blocks" => " блок",
                " chunks" => " чанк",
                " hearts" => " жүрек",
                " ticks" => " тик",
                " ms" => " мс",
                " px" => " пкс",
                " s" => " с",
                " fights" => " шайқас",
                "% of usual" => "% әдеттегіден",
                _ => u,
            }
        }
        Lang::Ru => {}
    }
    match u {
        " blocks" => " бл.",
        " chunks" => " чанк.",
        " hearts" => " серд.",
        " ticks" => " тик.",
        " ms" => " мс",
        " px" => " пкс",
        " s" => " с",
        " fights" => " боёв",
        "% of usual" => "% от обычной",
        _ => u,
    }
}

/// The words crossing over to a new language: the last frame in the old ones fades out as the new fades in (the menu's
/// and the HUD's own frames; the menus' screens do the same in menus/mod.rs).
pub struct Crossfade {
    last: Vec<f32>,
    ghost: Option<(Vec<f32>, std::time::Instant)>,
    seen: u32,
}

impl Crossfade {
    pub const fn new() -> Crossfade {
        Crossfade { last: Vec::new(), ghost: None, seen: 0 }
    }

    pub fn apply(&mut self, c: &mut super::draw::Canvas) {
        let v = crate::menus::lang::version();
        if v != self.seen {
            self.seen = v;
            if !self.last.is_empty() {
                self.ghost = Some((std::mem::take(&mut self.last), std::time::Instant::now()));
            }
        }
        self.last.clear();
        self.last.extend_from_slice(&c.p);
        if let Some((old, at)) = &self.ghost {
            let t = (at.elapsed().as_secs_f32() / 0.5).clamp(0.0, 1.0);
            let smooth = |a: f32, b: f32| {
                let x = ((t - a) / (b - a)).clamp(0.0, 1.0);
                x * x * (3.0 - 2.0 * x)
            };
            if t >= 1.0 {
                self.ghost = None;
            } else {
                // the old words go a little ahead of the new coming in
                c.fade_from(0, smooth(0.3, 1.0));
                let fresh = std::mem::take(&mut c.p);
                c.p.extend_from_slice(old);
                c.fade_from(0, 1.0 - smooth(0.0, 0.6));
                c.p.extend_from_slice(&fresh);
            }
        }
    }
}
